"""ปกปิดข้อมูลส่วนตัวในข้อความ ใช้ร่วมกันทั้งประวัติ (detection_history) และการ์ด LINE (flex_cards).

แยกไฟล์ไว้ไม่ให้มี import Supabase/config เพื่อให้การ์ดเรียกใช้ได้โดยไม่ต่อฐานข้อมูล
"""
import re


# redact_phone: ปิดเบอร์มือถือไทยที่มีคำว่า เบอร์/โทร นำหน้า
def redact_phone(text: str | None) -> str | None:
    """ปกปิดเฉพาะเบอร์มือถือไทยที่มีคำกำกับ เพื่อลดการจับเลขทั่วไปผิด."""
    if text is None:
        return None

    pattern = (
        r"((?:เบอร์โทรศัพท์|เบอร์โทร|เบอร์|โทรศัพท์|โทร)"
        r"\s*[:：]?\s*)"
        r"(?:0|\+66[ -]?)[689](?:[ -]?[0-9]){8}(?![0-9])"
    )
    return re.sub(pattern, r"\1[ปกปิดเบอร์โทร]", text)
